let current = "zh-CN";
let listeners = [];

export function detectLanguage() {
  const nav = (navigator.language || "en").toLowerCase();
  if (nav.startsWith("zh-tw") || nav.startsWith("zh-hk") || nav.startsWith("zh-hant")) return "zh-TW";
  if (nav.startsWith("zh")) return "zh-CN";
  if (nav.startsWith("ru")) return "ru";
  if (nav.startsWith("fr")) return "fr";
  if (nav.startsWith("de")) return "de";
  if (nav.startsWith("la")) return "la";
  if (nav.startsWith("en")) return "en";
  return "en";
}

export function resolveLanguage(pref) {
  if (!pref || pref === "auto") return detectLanguage();
  return SUPPORTED.includes(pref) ? pref : "en";
}

export function t(key) {
  return (dict[current] && dict[current][key]) || dict.en[key] || key;
}

export function getLanguage() {
  return current;
}

export function setLanguage(pref) {
  current = resolveLanguage(pref);
  document.documentElement.lang = current;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.getAttribute("data-i18n-aria")));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.getAttribute("data-i18n-title")));
  });
  listeners.forEach((fn) => fn(current));
}

export function onLanguageChange(fn) {
  listeners.push(fn);
}
